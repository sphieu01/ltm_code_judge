package com.grading.client.protocol;

/**
 * Enum chứa tất cả message types trong protocol.
 * Client và Server phải dùng CHUNG enum này.
 */
public enum MessageType {
    // Auth
    LOGIN,
    REGISTER,
    LOGIN_RESPONSE,
    REGISTER_RESPONSE,
    CHANGE_PASSWORD,
    CHANGE_PASSWORD_RESPONSE,

    // Problems
    GET_PROBLEMS,
    GET_PROBLEMS_RESPONSE,
    GET_PROBLEM_DETAIL,
    GET_PROBLEM_DETAIL_RESPONSE,
    CREATE_PROBLEM,
    CREATE_PROBLEM_RESPONSE,
    TOGGLE_PROBLEM_ACTIVE,
    TOGGLE_PROBLEM_ACTIVE_RESPONSE,

    // Academic Management (Teacher / Admin)
    GET_COURSES,
    GET_COURSES_RESPONSE,
    CREATE_COURSE,
    CREATE_COURSE_RESPONSE,
    GET_CLASSES,
    GET_CLASSES_RESPONSE,
    CREATE_CLASS,
    CREATE_CLASS_RESPONSE,
    UPDATE_CLASS,
    UPDATE_CLASS_RESPONSE,
    DELETE_CLASS,
    DELETE_CLASS_RESPONSE,
    GET_STUDENTS,
    GET_STUDENTS_RESPONSE,
    IMPORT_STUDENTS,
    IMPORT_STUDENTS_RESPONSE,
    UPDATE_STUDENT,
    UPDATE_STUDENT_RESPONSE,
    DELETE_STUDENT,
    DELETE_STUDENT_RESPONSE,
    GET_MY_CLASSES,
    GET_MY_CLASSES_RESPONSE,
    TOGGLE_COURSE_ACTIVE,
    TOGGLE_COURSE_ACTIVE_RESPONSE,

    // Submissions
    SUBMIT,
    SUBMIT_RESPONSE,
    GET_RESULT,
    GET_RESULT_RESPONSE,
    GET_HISTORY,
    GET_HISTORY_RESPONSE,

    // Notifications
    JUDGE_NOTIFICATION,

    // Connection
    DISCONNECT,

    // Error
    ERROR
}
